using System.Linq;

namespace Content.Client.Newton.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class NewResearchConsoleItem : LayoutContainer
{
    public TechnologyPrototype Prototype;
    public Action<ProtoId<TechnologyPrototype>, ResearchStatus>? SelectAction;
    private Color _color;
    private Color _borderColor;
    private Color _hoveredColor;

    public NewResearchConsoleItem(TechnologyPrototype proto, IPrototypeManager prototype, SpriteSystem sprite, ResearchStatus status)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Prototype = proto;

        ResearchDisplay.Texture = sprite.Frame0(proto.Icon);

        // if (prototype.TryIndex(proto.Discipline, out var discipline))
        //     _borderColor = discipline.Color;

        Button.ToolTip = Loc.GetString("research-console-menu-tooltip", ("cost", proto.Cost));

        Button.OnPressed += _ => SelectAction?.Invoke(Prototype.ID, status);

        Button.OnMouseEntered += _ =>
        {
            var panel = (StyleBoxFlat)Panel.PanelOverride!;
            panel.BackgroundColor = _hoveredColor;
        };
        Button.OnMouseExited += _ =>
        {
            var panel = (StyleBoxFlat)Panel.PanelOverride!;
            panel.BackgroundColor = _color;
        };

        (_color, _hoveredColor, _borderColor) = status switch
        {
            ResearchStatus.Researched => (Color.DarkOliveGreen, Color.PaleGreen, Color.LimeGreen),
            ResearchStatus.Available => (Color.FromHex("#7c7d2a"), Color.FromHex("#ecfa52"), Color.FromHex("#e8fa25")),
            ResearchStatus.Prerequisites => (Color.FromHex("#6b572f"), Color.FromHex("#fad398"), Color.FromHex("#cca031")),
            ResearchStatus.Unavailable => (Color.DarkRed, Color.PaleVioletRed, Color.Crimson),
        };

        SetColor();
    }

    public void SetScale(float scale)
    {
        NodeContainer.SetSize = new Vector2(80 * scale, 80 * scale);
    }

    private void SetColor()
    {
        var panel = (StyleBoxFlat)Panel.PanelOverride!;
        panel.BackgroundColor = Button.IsHovered ? _hoveredColor : _color;

        panel.BorderColor = _borderColor;
    }
}