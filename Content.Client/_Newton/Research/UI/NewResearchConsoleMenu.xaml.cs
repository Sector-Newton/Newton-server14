[GenerateTypedNameReferences]
public sealed partial class NewResearchConsoleMenu : FancyWindow
{
    public Action<string>? OnTechnologyResearchPressed;
    public Action? OnServerButtonPressed;

    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IResourceCache _resourceCache = default!;
    private readonly ResearchSystem _research;
    private readonly SpriteSystem _sprite;
    private readonly AccessReaderSystem _accessReader;

    public EntityUid Entity;
    public Dictionary<string, ResearchStatus> ResearchStatusDict = new();
    private bool _draggin;

    private Vector2 _position = new(580, 425);
    private float _zoom = 1f;
    private const float MinZoom = 0.5f;
    private const float MaxZoom = 2f;
    private const float ZoomSpeed = 0.125f;
    private const float IndentPos = 150f;

    private ProtoId<TechDisciplinePrototype>? _selectedDiscipline = "Industrial";
    private ProtoId<TechnologyPrototype>? _selectedTechnology;

    public NewResearchConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _research = _entity.System<ResearchSystem>();
        _sprite = _entity.System<SpriteSystem>();
        _accessReader = _entity.System<AccessReaderSystem>();

        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        RecenterButton.OnPressed += _ => Recenter();
        DragContainer.OnKeyBindDown += OnKeybindDown;
        DragContainer.OnKeyBindUp += OnKeybindUp;

        var textureResource = _resourceCache.GetResource<TextureResource>("/Textures/_Newton/Interface/UI/Research/console_menu.png");
        var styleBox = new StyleBoxTexture { Texture = textureResource.Texture };
        styleBox.SetPatchMargin(StyleBox.Margin.All, 10);
        ResearchesContainer.PanelOverride = styleBox;

        Recenter();
    }

    public void SetEntity(EntityUid entity)
    {
        Entity = entity;
    }

    public void UpdateItems(Dictionary<string, ResearchStatus> dict)
    {
        DragContainer.Children.Clear();
        ResearchStatusDict = dict;

        foreach (var techDict in ResearchStatusDict)
        {
            var tech = _prototype.Index<TechnologyPrototype>(techDict.Key);

            if (tech.Discipline == _selectedDiscipline)
            {
                var item = new NewResearchConsoleItem(tech, _prototype, _sprite, techDict.Value);
                item.SetScale(_zoom);

                item.SelectAction += SelectTechnology;

                if (techDict.Key == _selectedTechnology)
                    SelectTechnology(techDict.Key, techDict.Value);

                DragContainer.AddChild(item);
                var pos = tech.UIPos * IndentPos;
                LayoutContainer.SetPosition(item, _position + pos * _zoom);
            }
        }
    }

    public void UpdateInformationPanel(ResearchConsoleBoundInterfaceState state)
    {
        var amountMsg = new FormattedMessage();
        amountMsg.AddMarkupOrThrow(Loc.GetString("research-console-menu-research-points-text",
            ("points", state.Points)));
        ResearchAmountLabel.SetMessage(amountMsg);

        var msg = new FormattedMessage();
        msg.AddMarkupOrThrow(Loc.GetString("research-console-menu-crypto-text",
            ("crypto", 0)));
        CryptoLabel.SetMessage(msg);

        if (!_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database))
            return;

        TierDisplayContainer.Children.Clear();
        foreach (var disciplineId in database.SupportedDisciplines)
        {
            var discipline = _prototype.Index<TechDisciplinePrototype>(disciplineId);
            var button = new Button { Text = discipline.UIName };
            button.OnPressed += _ => SelectDiscipline(disciplineId);

            var control = new BoxContainer
            {
                Children =
                {
                    button,
                    new Control
                    {
                        MinWidth = 10
                    }
                }
            };
            TierDisplayContainer.AddChild(control);
        }

        foreach (var disciplineId in database.SupportedDisciplines)
        {
            var discipline = _prototype.Index<TechDisciplinePrototype>(disciplineId);
            var percentage = _research.GetTierPercentage(database, discipline);

            var texture = new TextureRect
            {
                TextureScale = new Vector2(2, 2),
                VerticalAlignment = VAlignment.Center
            };
            var label = new RichTextLabel();
            texture.Texture = _sprite.Frame0(discipline.Icon);
            label.SetMessage(Loc.GetString("research-console-tier-info-small-percentage", ("percentage", percentage)));

            var control = new BoxContainer
            {
                Children =
                {
                    texture,
                    label,
                    new Control
                    {
                        MinWidth = 10
                    }
                }
            };
            TierDisplayContainer.AddChild(control);
        }
    }

    private void SelectDiscipline(ProtoId<TechDisciplinePrototype> disciplineId)
    {
        _selectedDiscipline = disciplineId;
        UpdateItems(ResearchStatusDict);
        Recenter();
    }

    private void SelectTechnology(ProtoId<TechnologyPrototype> technologyId, ResearchStatus status)
    {
        InfoContainer.RemoveAllChildren();

        if (!_player.LocalEntity.HasValue)
            return;

        if (!_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database))
            return;

        _selectedTechnology = technologyId;
        var tech = _prototype.Index<TechnologyPrototype>(technologyId);

        var control = new TechnologyInfoPanel(tech, _sprite, _prototype, _research, status, _accessReader.IsAllowed(_player.LocalEntity.Value, Entity), database);
        control.ResearchAction += args => OnTechnologyResearchPressed?.Invoke(args.ID);

        InfoContainer.AddChild(control);
    }

    #region Drag handle
    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (!_draggin)
            return;

        _position += args.Relative;

        foreach (var child in DragContainer.Children)
        {
            LayoutContainer.SetPosition(child, child.Position + args.Relative);
        }
    }

    protected override void MouseWheel(GUIMouseWheelEventArgs args)
    {
        base.MouseWheel(args);

        var oldZoom = _zoom;

        if (args.Delta.Y > 0)
            _zoom += ZoomSpeed;
        else
            _zoom -= ZoomSpeed;

        _zoom = Math.Clamp(_zoom, MinZoom, MaxZoom);

        if (MathHelper.CloseTo(oldZoom, _zoom))
            return;

        foreach (var child in DragContainer.Children)
        {
            if (child is not NewResearchConsoleItem item)
                continue;

            var pos = item.Prototype.UIPos * IndentPos;
            LayoutContainer.SetPosition(child, _position + pos * _zoom);
            item.SetScale(_zoom);
        }
        args.Handle();
    }

    private void OnKeybindDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _draggin = true;
    }

    private void OnKeybindUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _draggin = false;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return _draggin ? DragMode.None : base.GetDragModeFor(relativeMousePos);
    }

    private void Recenter()
    {
        _position = new(580, 425);
        foreach (var child in DragContainer.Children)
        {
            if (child is not NewResearchConsoleItem item)
                continue;

            var pos = item.Prototype.UIPos * IndentPos;
            LayoutContainer.SetPosition(child, _position + pos * _zoom);
            item.SetScale(_zoom);
        }
        InfoContainer.RemoveAllChildren();
    }
    #endregion
}

// Taken from orion and goobstation, and changed
public sealed class ResearchesContainerPanel : LayoutContainer
{
    private const int DashedLineDistanceThreshold = 6;
    private const int MaxLineDistanceThreshold = 12;
    private const float DashLength = 8f;
    private const float DashGap = 5f;

    protected override void Draw(DrawingHandleScreen handle)
    {
        var items = new Dictionary<string, NewResearchConsoleItem>();
        foreach (var child in Children.OfType<NewResearchConsoleItem>())
        {
            items.TryAdd(child.Prototype.ID, child);
        }

        foreach (var item in items.Values)
        {
            if (item.Prototype.TechnologyPrerequisites.Count <= 0)
                continue;

            foreach (var prerequisiteId in item.Prototype.TechnologyPrerequisites)
            {
                if (!items.TryGetValue(prerequisiteId, out var prerequisite))
                    continue;

                DrawConnection(handle, item, prerequisite, Color.White);
            }
        }
    }

    private static void DrawConnection(DrawingHandleScreen handle, NewResearchConsoleItem item, NewResearchConsoleItem prerequisite, Color color)
    {
        var delta = item.Prototype.UIPos - prerequisite.Prototype.UIPos;
        var distanceInCells = Math.Abs(delta.X) + Math.Abs(delta.Y);
        if (distanceInCells > MaxLineDistanceThreshold)
            return;

        var isDashed = distanceInCells > DashedLineDistanceThreshold;

        var itemCenter = GetCenter(item);
        var prerequisiteCenter = GetCenter(prerequisite);

        if (delta.Y == 0)
        {
            var start = GetHorizontalEdge(itemCenter, item.PixelWidth, rightSide: delta.X < 0);
            var end = GetHorizontalEdge(prerequisiteCenter, prerequisite.PixelWidth, rightSide: delta.X >= 0);
            DrawConnectionLine(handle, start, end, isDashed, color);
            return;
        }

        var startEdge = GetHorizontalEdge(itemCenter, item.PixelWidth, rightSide: delta.X < 0);
        var endEdge = GetHorizontalEdge(prerequisiteCenter, prerequisite.PixelWidth, rightSide: delta.X >= 0);
        var corridorX = (startEdge.X + endEdge.X) / 2f;

        DrawConnectionLine(handle, startEdge, new Vector2(corridorX, startEdge.Y), isDashed, color);
        DrawConnectionLine(handle, new Vector2(corridorX, startEdge.Y), new Vector2(corridorX, endEdge.Y), isDashed, color);
        DrawConnectionLine(handle, new Vector2(corridorX, endEdge.Y), endEdge, isDashed, color);
    }

    private static Vector2 GetCenter(NewResearchConsoleItem item)
    {
        return new Vector2(item.PixelPosition.X + item.PixelWidth / 2f, item.PixelPosition.Y + item.PixelHeight / 2f);
    }

    private static Vector2 GetHorizontalEdge(Vector2 center, float width, bool rightSide)
    {
        var offset = width / 2f;
        return center + new Vector2(rightSide ? offset : -offset, 0f);
    }

    private static void DrawConnectionLine(DrawingHandleScreen handle, Vector2 start, Vector2 end, bool dashed, Color color)
    {
        if (!dashed)
        {
            handle.DrawLine(start, end, color);
            return;
        }

        var direction = end - start;
        var length = direction.Length();
        if (length <= 0)
            return;

        var normalizedDirection = direction / length;
        for (var offset = 0f; offset < length; offset += DashLength + DashGap)
        {
            var dashEnd = Math.Min(offset + DashLength, length);
            handle.DrawLine(start + normalizedDirection * offset, start + normalizedDirection * dashEnd, color);
        }
    }
}