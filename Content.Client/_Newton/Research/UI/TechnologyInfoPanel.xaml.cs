using Robust.Shared.Localization;

namespace Content.Client.Newton.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class TechnologyInfoPanel : Control
{
    public TechnologyPrototype Prototype;
    public Action<TechnologyPrototype>? ResearchAction;

    public TechnologyInfoPanel(TechnologyPrototype proto, SpriteSystem sprite, IPrototypeManager prototype, ResearchSystem research, ResearchStatus status, bool hasAccess, TechnologyDatabaseComponent? db = null)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Prototype = proto;

        TechnologyNameLabel.Text = Loc.GetString(proto.Name);
        DisciplineTexture.Texture = sprite.Frame0(prototype.Index(proto.Discipline).Icon);
        TechnologyTexture.Texture = sprite.Frame0(proto.Icon);

        ResearchButton.ToolTip = !hasAccess
            ? Loc.GetString("research-console-no-access-popup")
            : null;

        ResearchButton.Text = status == ResearchStatus.Researched
            ? Loc.GetString("research-console-menu-server-researched-button")
            : ResearchButton.Text;

        TechnologyDescriptionLabel.SetMessage(research.GetTechnologyDescription(proto, false, false, true));

        var costColor = status switch
        {
            ResearchStatus.Researched => "purple",
            ResearchStatus.Available => "green",
            ResearchStatus.Unavailable => "red",
            ResearchStatus.Prerequisites => "red",
        };

        var costMessage = new FormattedMessage();
        costMessage.AddMarkupOrThrow(Loc.GetString("research-console-info-cost-title"));
        costMessage.PushNewline();
        costMessage.AddMarkupOrThrow(Loc.GetString("research-console-info-cost-label", ("color", costColor), ("cost", proto.Cost)));
        TechnologyCostLabel.SetMessage(costMessage);

        ResearchButton.Disabled = !hasAccess || status != ResearchStatus.Available;
        ResearchButton.OnPressed += _ => ResearchAction?.Invoke(Prototype);
    }
}